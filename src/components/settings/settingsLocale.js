const fallbackLanguage = (lang) => (copy[lang] ? lang : lang === 'zh' ? 'zh' : 'en')

export const settingsLanguage = computed(() => language.value)

export const setSettingsLanguage = (lang) => {
  if (!settingsLanguages[lang]) return
  language.value = lang
  setAppLanguage(lang)
  document.documentElement.setAttribute('data-language', lang)
}

export const st = (key) => {
  const lang = fallbackLanguage(language.value)
  return copy[lang]?.[key] || copy.zh[key] || key
}
